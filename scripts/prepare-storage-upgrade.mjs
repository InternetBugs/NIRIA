import { extractAll, extractFile } from "@electron/asar";
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import assert from "node:assert/strict";

const root = fileURLToPath(new URL("../", import.meta.url));
const v2 = process.argv.includes("--v2");
const oldVersion = v2 ? "0.14.0" : "0.7.0";
const archive = join(root, "release", "win-unpacked", "resources", "app.asar");
const bundle = JSON.parse(extractFile(archive, "package.json").toString());
assert.equal(bundle.version, oldVersion, `prepare using the verified old ${oldVersion} package before building the new package`);
const folder = join(root, "artifacts", `storage${v2 ? "-v2" : ""}-upgrade-${Date.now()}`);
const runtime = join(folder, "legacy-runtime"), dataDirectory = join(folder, "data");
await mkdir(dataDirectory, { recursive: true });
extractAll(archive, runtime);
const { CompanionStore } = await import(pathToFileURL(join(runtime, "core", "store.mjs")));
const { SyncService } = await import(pathToFileURL(join(runtime, "core", "sync-service.mjs")));
const { encryptBackup } = await import(pathToFileURL(join(runtime, "core", "backup.mjs")));
const store = new CompanionStore(join(dataDirectory, "companion.sqlite")), sync = new SyncService(store);
sync.createPair();
store.identity({ name: "旧版升级验证", userName: "隔离测试" });
const source = store.addUser("旧版的共同经历");
const memory = store.addMemory({ content: "保留旧版的记忆来源", sources: [{ id: source.id, revision: 1 }] });
store.editMemory(memory, { allowModel: false, allowSync: false });
const forgotten = store.addUser("升级前已经删除");
store.deleteMessage(forgotten.id);
const png = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=";
store.mutate((state) => { state.avatar = { format: "niria-avatar-prototype", version: 1, source: png, actions: { smile: png },
  ...(v2 ? { background: { version: 1, mode: "edge-connected" } } : {}) }; });
const expected = store.snapshot(), syncMeta = structuredClone(sync.meta);
const backup = await encryptBackup(store.exportData(), "isolated-old-version-backup");
const oldSchema = store.db.prepare("PRAGMA user_version").get().user_version;
assert.equal(oldSchema, v2 ? 2 : 0);
await writeFile(join(dataDirectory, "upgrade-expected.json"), JSON.stringify({ oldVersion: bundle.version, oldSchema, expected, syncMeta }));
await writeFile(join(dataDirectory, "legacy-backup.niria"), JSON.stringify(backup));
store.close();
const pointer = join(root, "artifacts", v2 ? "storage-v2-upgrade-fixture.json" : "storage-upgrade-fixture.json");
await writeFile(pointer, JSON.stringify({ dataDirectory, oldVersion: bundle.version }));
assert.equal(JSON.parse(await readFile(pointer, "utf8")).oldVersion, oldVersion);
console.log(JSON.stringify({ preparedFrom: bundle.version, oldSchema, dataDirectory, encryptedBackup: true }));
